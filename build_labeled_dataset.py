# ─────────────────────────────────────────────────────────────────────────────
# THRESHOLD HELPERS
# ─────────────────────────────────────────────────────────────────────────────

def _compute_atr(df: pd.DataFrame, window: int = 14) -> pd.Series:
    """
    Exponential ATR using Wilder-style EMA on True Range.
    True Range = max(H−L, |H−prev_C|, |L−prev_C|).
    """
    prev_close = df["Close"].shift(1)
    tr = pd.concat([
        df["High"] - df["Low"],
        (df["High"] - prev_close).abs(),
        (df["Low"]  - prev_close).abs(),
    ], axis=1).max(axis=1)
    return tr.ewm(span=window, adjust=False).mean()


def _build_threshold(df: pd.DataFrame) -> pd.Series:
    """
    Return a per-bar threshold Series expressed as a return fraction.
    Values are always positive; applied symmetrically (±threshold).
    """
    close = df["Close"].squeeze()

    if LABEL_METHOD == "fixed_pct":
        # Same percentage threshold for every bar
        return pd.Series(PCT_THRESHOLD, index=df.index)

    elif LABEL_METHOD == "atr_mult":
        # Volatility-adaptive: wider threshold during high-volatility regimes
        atr = _compute_atr(df)
        return (atr / close) * ATR_MULT

    elif LABEL_METHOD == "rolling_std":
        # Sigma-based: threshold scales with recent return dispersion
        returns = close.pct_change()
        return returns.rolling(20, min_periods=5).std() * STD_MULT

    else:
        raise ValueError(
            f"Unknown LABEL_METHOD='{LABEL_METHOD}'. "
            "Choose 'fixed_pct', 'atr_mult', or 'rolling_std'."
        )


# ─────────────────────────────────────────────────────────────────────────────
# SIGNAL LABELLING
# ─────────────────────────────────────────────────────────────────────────────

def label_signals(df: pd.DataFrame) -> pd.Series:
    """
    Assign a BUY / HOLD / SELL label to every bar using the forward return
    over the next FORWARD_BARS bars:

        fwd_return = (close[t + FORWARD_BARS] / close[t]) − 1

    Decision rules
    --------------
    fwd_return >  threshold  →  BUY  (2)
    fwd_return < −threshold  →  SELL (0)
    otherwise                →  HOLD (1)

    The last FORWARD_BARS rows receive NaN because there is no future
    close to compute a forward return from.

    Returns
    -------
    pd.Series (float): 2.0=BUY, 1.0=HOLD, 0.0=SELL, NaN=unlabelable tail.
    """
    close      = df["Close"].squeeze()
    fwd_return = close.shift(-FORWARD_BARS) / close - 1   # look-ahead return
    threshold  = _build_threshold(df)

    # Start everything as NaN; only fill where both signals are valid
    signal = pd.Series(np.nan, index=df.index, dtype=float)
    valid  = fwd_return.notna() & threshold.notna()

    # The three regions are mutually exclusive by construction:
    #   BUY:  fwd_return > threshold            (strictly above)
    #   SELL: fwd_return < -threshold           (strictly below)
    #   HOLD: -threshold ≤ fwd_return ≤ threshold
    signal.loc[valid & (fwd_return >  threshold)] = BUY
    signal.loc[valid & (fwd_return < -threshold)] = SELL
    signal.loc[
        valid &
        (fwd_return >= -threshold) &
        (fwd_return <=  threshold)
    ] = HOLD

    return signal


# ─────────────────────────────────────────────────────────────────────────────
# PIPELINE
# ─────────────────────────────────────────────────────────────────────────────

def build_labeled_dataset(
    ticker:   str = TICKER,
    period:   str = PERIOD,
    interval: str = INTERVAL,
) -> pd.DataFrame:
    """
    End-to-end pipeline:
        download OHLCV → build all features → label → return clean DataFrame

    The returned DataFrame has:
        - Raw OHLCV reference columns (Open, High, Low, Volume) for context
        - All feature columns defined in ALL_FEATURE_COLS (whichever exist)
        - 'target' column  →  int: 2=BUY, 1=HOLD, 0=SELL

    NaN handling strategy
    ----------------------
    1. Tail rows (last FORWARD_BARS bars — no future close available) → dropped
    2. FVG price-level columns (fvg_bull_top etc.) → filled with 0
       (NaN in those columns means "no active FVG zone", which is 0)
    3. All remaining feature NaN (indicator warm-up period) →
       forward-filled, then zero-filled for any edge cases at the very start
    """

    # ── 1. Download ──────────────────────────────────────────────────────────
    print(f"\n[1/4] Downloading {ticker}  period={period}  interval={interval} …")
    raw = yf.download(
        ticker, period=period, interval=interval,
        progress=False, auto_adjust=True
    )
    if isinstance(raw.columns, pd.MultiIndex):
        raw.columns = raw.columns.get_level_values(0)
    print(f"      {len(raw):,} bars downloaded.")

    # ── 2. Feature engineering ────────────────────────────────────────────────
    print("[2/4] Building all features …")
    print("      (Note: _add_structural_trend has an O(n·lookback) Python loop;")
    print("       expect ~20–40 s for 60 days of 5-min data.)")
    enriched = build_features(raw, period=period, interval=interval)
    print(f"      Done — {enriched.shape[1]} columns in enriched dataframe.")

    # ── 3. Label ─────────────────────────────────────────────────────────────
    bar_num  = int("".join(filter(str.isdigit, interval)))  # numeric part, e.g. 5
    bar_unit = interval[-1]                                  # time unit,    e.g. "m"
    print(
        f"[3/4] Labelling with method='{LABEL_METHOD}', "
        f"forward_bars={FORWARD_BARS} "
        f"(≈ {FORWARD_BARS * bar_num} {bar_unit} look-ahead) …"
    )
    enriched["target"] = label_signals(enriched)

    # ── 4. Column selection ───────────────────────────────────────────────────
    # Keep raw OHLCV for reference; feature cols; target
    ref_ohlcv = ["Open", "High", "Low", "Volume"]

    feat_cols = [c for c in ALL_FEATURE_COLS if c in enriched.columns]
    missing   = [
        c for c in ALL_FEATURE_COLS
        if c not in enriched.columns and c not in _NEWS_COLS
    ]
    if missing:
        print(f"      ⚠  {len(missing)} expected feature column(s) not found "
              f"in enriched df: {missing}")

    # Build ordered, deduplicated keep list
    keep    = list(dict.fromkeys(ref_ohlcv + feat_cols + ["target"]))
    keep    = [c for c in keep if c in enriched.columns]
    dataset = enriched[keep].copy()

    # ── 5. NaN handling ───────────────────────────────────────────────────────
    n_before = len(dataset)

    # (a) Drop unlabelable tail rows (forward return undefined)
    dataset = dataset.dropna(subset=["target"])

    # (b) FVG zone price-level NaN → 0  ("not inside any FVG" = 0)
    fvg_fill = [c for c in _FVG_ZONE_COLS if c in dataset.columns]
    if fvg_fill:
        dataset[fvg_fill] = dataset[fvg_fill].fillna(0)

    # (c) Remaining feature NaN (indicator warm-up) → ffill then 0-fill
    dataset[feat_cols] = dataset[feat_cols].ffill().fillna(0)

    n_after = len(dataset)
    print(f"      Removed {n_before - n_after:,} tail rows. "
          f"{n_after:,} rows remain.")

    # Cast target to int now that all NaN rows are gone
    dataset["target"] = dataset["target"].astype(int)

    # ── 6. Summary ────────────────────────────────────────────────────────────
    total = len(dataset)
    print(f"\n[4/4] Labeled dataset summary")
    print(f"      Ticker          : {ticker}")
    print(f"      Period/Interval : {period} / {interval}")
    print(f"      Label method    : {LABEL_METHOD}", end="")
    if   LABEL_METHOD == "fixed_pct":
        print(f"  (threshold = ±{PCT_THRESHOLD:.3%})")
    elif LABEL_METHOD == "atr_mult":
        print(f"  (threshold = {ATR_MULT}× ATR14 / Close)")
    elif LABEL_METHOD == "rolling_std":
        print(f"  (threshold = {STD_MULT}× 20-bar σ of returns)")
    print(f"      Forward bars    : {FORWARD_BARS} "
          f"(≈ {FORWARD_BARS * bar_num} {bar_unit} look-ahead)")
    print(f"      Feature columns : {len(feat_cols)}")
    print(f"      Total rows      : {total:,}")
    print(f"\n      Class distribution:")

    for code in [BUY, HOLD, SELL]:
        cnt  = (dataset["target"] == code).sum()
        name = LABEL_NAMES[code]
        bar  = "█" * max(1, int(30 * cnt / total))
        print(f"        {name:4s} (code={code})  {cnt:6,}  ({100 * cnt / total:5.1f}%)  {bar}")

    imbalance_ratio = (
        (dataset["target"] == BUY).sum()
        / max(1, (dataset["target"] == SELL).sum())
    )
    if imbalance_ratio > 3 or imbalance_ratio < 0.33:
        print(f"\n      ⚠  BUY/SELL ratio = {imbalance_ratio:.2f}. "
              "Consider class weighting or SMOTE in your model.")

    return dataset


